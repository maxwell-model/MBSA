"""Unified aligned-plan ABI for provisional Top-32 block-sparse GQA.

The prefill dispatch consumes this plan for contiguous and paged KV,
including partial final Q and KV blocks.
CPU references losslessly split and rebuild the frozen C123 route.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from enum import Enum
from typing import Optional

import torch


class KvLayout(str, Enum):
    CONTIGUOUS_NHD = "contiguous_nhd"
    PAGED_PHTD = "paged_phtd"


class PrefillPolicy(str, Enum):
    ALIGNED_CONTIGUOUS = "aligned_contiguous"
    ALIGNED_PAGED = "aligned_paged"


@dataclass(frozen=True)
class SparseAttentionSpec:
    block_size: int = 128
    prefix_blocks: int = 8
    dynamic_topk: int = 16
    local_swa_blocks: int = 8
    q_heads: int = 32
    kv_heads: int = 4
    head_dim: int = 128
    q_dtype: torch.dtype = torch.bfloat16
    kv_dtype: torch.dtype = torch.bfloat16

    @property
    def group_size(self) -> int:
        return self.q_heads // self.kv_heads

    @property
    def topk(self) -> int:
        return self.prefix_blocks + self.dynamic_topk + self.local_swa_blocks

    def validate(self) -> None:
        if self.block_size != 128:
            raise ValueError("unified backend is specialized to block size 128")
        if (self.prefix_blocks, self.dynamic_topk, self.local_swa_blocks) != (
            8,
            16,
            8,
        ):
            raise ValueError("unified backend is specialized to prefix8/dynamic16/SWA8")
        if (self.q_heads, self.kv_heads, self.head_dim) != (32, 4, 128):
            raise ValueError("unified backend is specialized to Hq/Hkv/D=32/4/128")
        if self.q_heads % self.kv_heads:
            raise ValueError("q_heads must be divisible by kv_heads")
        if self.q_dtype != torch.bfloat16 or self.kv_dtype != torch.bfloat16:
            raise ValueError("unified backend is BF16-only")


SPEC = SparseAttentionSpec()
SPEC.validate()


def dynamic_partial_capacity(skv: int) -> int:
    """Bound partial storage to the public MSA capacities 4, 8 and 16."""
    if skv <= 0:
        raise ValueError("Skv must be positive")
    blocks = (skv + SPEC.block_size - 1) // SPEC.block_size
    live = min(SPEC.dynamic_topk, max(0, blocks - SPEC.prefix_blocks - SPEC.local_swa_blocks))
    return 1 << (max(4, live) - 1).bit_length()


def use_unified_aligned_prefill(*, sq: int, skv: int) -> bool:
    """Return the supported batch-one prefill dispatch range, including tails."""
    return (
        1 <= sq <= 8192
        and 1 <= skv <= 1048576
        and sq <= skv
    )


@dataclass
class FwdTilePlan:
    """Runtime buffers for the V1 two-view consumer-native plan.

    ``dynamic_route`` is the exact dynamic set, not the final Top-32 route.
    Prefix and SWA blocks are generated by the fixed-state consumer.  CSR and
    schedule tensors are opaque here because their concrete Python type is
    owned by the vendored MSA backend. ``q_offset_tokens`` is an integer for
    batch one and a request-ordered tuple for packed variable-sequence Q.
    """

    dynamic_route: torch.Tensor
    page_table: torch.Tensor
    valid_kv_tokens: torch.Tensor
    q_offset_tokens: int | tuple[int, ...]
    policy: PrefillPolicy
    dynamic_csr: Optional[tuple[torch.Tensor, torch.Tensor, object]] = None

    def validate(self, *, sq: int, skv: int, device: torch.device) -> None:
        if sq <= 0 or skv <= 0 or sq > skv:
            raise ValueError("require 0 < Sq <= Skv")
        if self.q_offset_tokens != skv - sq:
            raise ValueError("q_offset_tokens must equal Skv - Sq")
        expected = (SPEC.kv_heads, sq, SPEC.dynamic_topk)
        if tuple(self.dynamic_route.shape) != expected:
            raise ValueError(f"dynamic_route must have shape {expected}")
        if self.dynamic_route.dtype != torch.int32:
            raise ValueError("dynamic_route must be int32")
        if self.dynamic_route.device != device or not self.dynamic_route.is_contiguous():
            raise ValueError("dynamic_route must be contiguous on the Q device")
        if self.page_table.dtype != torch.int32 or self.page_table.device != device:
            raise ValueError("page_table must be int32 on the Q device")
        if self.valid_kv_tokens.dtype != torch.int32 or self.valid_kv_tokens.device != device:
            raise ValueError("valid_kv_tokens must be int32 on the Q device")

    def validate_packed(
        self,
        *,
        q_lens: Sequence[int],
        kv_lens: Sequence[int],
        device: torch.device,
    ) -> None:
        """Validate a packed variable-sequence plan without changing route IDs.

        Dynamic route entries remain request-local logical KV block IDs.  The
        native CSR builder uses the packed prefix sums to assign each entry to
        its request, while the fixed BSA scheduler uses request-local tile descriptors
        so a partial final Q tile cannot cross a sequence boundary.
        """
        if not q_lens or len(q_lens) != len(kv_lens):
            raise ValueError("q_lens and kv_lens must describe the same non-empty batch")
        if any(q <= 0 or k < q for q, k in zip(q_lens, kv_lens)):
            raise ValueError("each request must satisfy 0 < Sq <= Skv")
        offsets = tuple(k - q for q, k in zip(q_lens, kv_lens))
        declared_offsets = (
            (self.q_offset_tokens,)
            if isinstance(self.q_offset_tokens, int)
            else tuple(self.q_offset_tokens)
        )
        if declared_offsets != offsets:
            raise ValueError("q_offset_tokens must equal per-request Skv - Sq")
        expected = (SPEC.kv_heads, sum(q_lens), SPEC.dynamic_topk)
        if tuple(self.dynamic_route.shape) != expected:
            raise ValueError(f"dynamic_route must have shape {expected}")
        if self.dynamic_route.dtype != torch.int32:
            raise ValueError("dynamic_route must be int32")
        if self.dynamic_route.device != device or not self.dynamic_route.is_contiguous():
            raise ValueError("dynamic_route must be contiguous on the Q device")
        if self.page_table.dtype != torch.int32 or self.page_table.device != device:
            raise ValueError("page_table must be int32 on the Q device")
        if self.policy == PrefillPolicy.ALIGNED_PAGED:
            max_pages = (max(kv_lens) + SPEC.block_size - 1) // SPEC.block_size
            if self.page_table.ndim != 2 or self.page_table.shape[0] != len(q_lens):
                raise ValueError("page_table must have one row per request")
            if self.page_table.shape[1] < max_pages:
                raise ValueError("page_table does not cover the longest KV sequence")
        if self.valid_kv_tokens.dtype != torch.int32 or self.valid_kv_tokens.device != device:
            raise ValueError("valid_kv_tokens must be int32 on the Q device")
        if tuple(self.valid_kv_tokens.shape) != (len(q_lens),):
            raise ValueError("valid_kv_tokens must have one entry per request")


def valid_block_count(q_global: int, *, skv: int, block_size: int = 128) -> int:
    if q_global < 0 or q_global >= skv:
        raise ValueError("query global position is outside the KV sequence")
    return min((q_global + block_size) // block_size, (skv + block_size - 1) // block_size)


def fixed_block_ids(valid_blocks: int, *, spec: SparseAttentionSpec = SPEC) -> list[int]:
    """Return the frozen sorted unique prefix/SWA union."""
    if valid_blocks < 0:
        raise ValueError("valid_blocks must be non-negative")
    prefix = range(min(spec.prefix_blocks, valid_blocks))
    local = range(max(0, valid_blocks - spec.local_swa_blocks), valid_blocks)
    return sorted(set(prefix).union(local))


def split_c123_route_reference(
    route: torch.Tensor,
    *,
    skv: int,
    q_offset: int,
    spec: SparseAttentionSpec = SPEC,
) -> torch.Tensor:
    """Extract exact dynamic16 rows from a CPU C123 Top-32 route.

    The function rejects rather than repairs any route that does not follow
    the frozen fixed-first C123 ordering or that contains duplicate/OOB IDs.
    """
    if route.device.type != "cpu" or route.dtype != torch.int32 or route.ndim != 3:
        raise ValueError("route must be CPU int32 [Hkv,Sq,32]")
    hkv, sq, topk = route.shape
    if (hkv, topk) != (spec.kv_heads, spec.topk):
        raise ValueError("route shape does not match the frozen Top-32 contract")
    if q_offset != skv - sq:
        raise ValueError("q_offset must equal Skv - Sq")
    dynamic = torch.full((hkv, sq, spec.dynamic_topk), -1, dtype=torch.int32)
    for q in range(sq):
        nblocks = valid_block_count(q_offset + q, skv=skv, block_size=spec.block_size)
        fixed = fixed_block_ids(nblocks, spec=spec)
        target = min(spec.topk, nblocks)
        fixed_count = len(fixed)
        dynamic_count = target - fixed_count
        for h in range(hkv):
            row = [int(x) for x in route[h, q].tolist()]
            live = row[:target]
            if row[target:] != [-1] * (spec.topk - target):
                raise ValueError("route padding is not canonical -1")
            if live[:fixed_count] != fixed:
                raise ValueError("route fixed prefix/SWA region is not canonical")
            dyn = live[fixed_count:]
            if len(dyn) != dynamic_count:
                raise ValueError("route dynamic count does not fill target cardinality")
            if len(set(live)) != len(live):
                raise ValueError("route contains duplicate blocks")
            if any(block < 0 or block >= nblocks for block in live):
                raise ValueError("route contains a causal-invalid or OOB block")
            if set(dyn).intersection(fixed):
                raise ValueError("dynamic route overlaps fixed support")
            if dyn:
                dynamic[h, q, : len(dyn)] = torch.tensor(dyn, dtype=torch.int32)
    return dynamic


def rebuild_c123_route_reference(
    dynamic_route: torch.Tensor,
    *,
    skv: int,
    q_offset: int,
    spec: SparseAttentionSpec = SPEC,
) -> torch.Tensor:
    """Rebuild canonical C123 Top-32 rows from the V1 dynamic view."""
    if (
        dynamic_route.device.type != "cpu"
        or dynamic_route.dtype != torch.int32
        or dynamic_route.ndim != 3
    ):
        raise ValueError("dynamic_route must be CPU int32 [Hkv,Sq,16]")
    hkv, sq, capacity = dynamic_route.shape
    if (hkv, capacity) != (spec.kv_heads, spec.dynamic_topk):
        raise ValueError("dynamic route shape does not match the V1 ABI")
    if q_offset != skv - sq:
        raise ValueError("q_offset must equal Skv - Sq")
    route = torch.full((hkv, sq, spec.topk), -1, dtype=torch.int32)
    for q in range(sq):
        nblocks = valid_block_count(q_offset + q, skv=skv, block_size=spec.block_size)
        fixed = fixed_block_ids(nblocks, spec=spec)
        target = min(spec.topk, nblocks)
        dynamic_count = target - len(fixed)
        for h in range(hkv):
            row = [int(x) for x in dynamic_route[h, q].tolist()]
            dyn = row[:dynamic_count]
            if row[dynamic_count:] != [-1] * (capacity - dynamic_count):
                raise ValueError("dynamic padding is not canonical -1")
            if len(set(dyn)) != len(dyn) or set(dyn).intersection(fixed):
                raise ValueError("dynamic route is duplicate or overlaps fixed support")
            if any(block < 0 or block >= nblocks for block in dyn):
                raise ValueError("dynamic route contains causal-invalid or OOB blocks")
            live = fixed + dyn
            route[h, q, : len(live)] = torch.tensor(live, dtype=torch.int32)
    return route


def packed_fixed_bsa_route_reference(
    *,
    sq: int,
    skv: int,
    spec: SparseAttentionSpec = SPEC,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Build the old explicit route used to validate implicit fixed support.

    This reference is block-aligned only.  The production candidate will
    generate the same IDs inside the BSA backend and will not publish them.
    """
    if sq <= 0 or skv < sq or sq % spec.block_size or skv % spec.block_size:
        raise ValueError("packed fixed BSA reference requires aligned 0 < Sq <= Skv")
    q_blocks = sq // spec.block_size
    packed_rows = q_blocks * spec.group_size
    route = torch.full((1, spec.kv_heads, packed_rows, 16), -1, dtype=torch.int32)
    counts = torch.zeros((1, spec.kv_heads, packed_rows), dtype=torch.int32)
    q_block_offset = (skv - sq) // spec.block_size
    for local_q_block in range(q_blocks):
        fixed = fixed_block_ids(q_block_offset + local_q_block + 1, spec=spec)
        for packed_head in range(spec.group_size):
            row = local_q_block * spec.group_size + packed_head
            route[0, :, row, : len(fixed)] = torch.tensor(fixed, dtype=torch.int32)
            counts[0, :, row] = len(fixed)
    return route, counts


